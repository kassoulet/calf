#!/usr/bin/env python3
"""
embed_assets.py — turn the Calf_Default GTK theme PNGs into a C++ header
with static byte arrays + a small NanoVG-image lookup table.

Output: calf-dpf/ui-lib/theme_assets.hpp

The DPF plugins ship as single .so files with no resource bundle, so
the theme art has to live inside the binary. NanoVG's
`nvgCreateImageMem` happily loads PNG bytes straight from memory; we
just need them addressable by name.
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
SRC  = REPO / "gui" / "styles" / "Calf_Default"
OUT  = REPO / "calf-dpf" / "ui-lib" / "theme_assets.hpp"

# Only embed the assets the DGL renderer actually uses today. Keeping
# this list narrow holds the binary size down — every plugin would
# otherwise carry ~1 MB of unused PNG.
ASSETS = [
    "background_plugin.png",
    "knob_1.png",
    "knob_2.png",
    "knob_3.png",
    "knob_4.png",
    "knob_5.png",
    "light_top.png",
    "light_bottom.png",
]

def c_ident(name: str) -> str:
    return name.replace(".", "_").replace("-", "_")

def emit():
    lines = []
    lines.append("// AUTO-GENERATED by calf-dpf/tools/embed_assets.py — do not edit.")
    lines.append("// Calf_Default GTK theme PNGs, embedded as byte arrays for")
    lines.append("// nvgCreateImageMem.")
    lines.append("#ifndef CALF_THEME_ASSETS_HPP")
    lines.append("#define CALF_THEME_ASSETS_HPP")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <cstring>")
    lines.append("")
    lines.append("namespace calf_theme {")
    lines.append("")

    for name in ASSETS:
        path = SRC / name
        if not path.exists():
            sys.stderr.write(f"missing asset: {path}\n")
            sys.exit(1)
        data = path.read_bytes()
        ident = c_ident(name)
        lines.append(f"// {name} ({len(data)} bytes)")
        lines.append(f"static const unsigned char {ident}[] = {{")
        row = []
        for i, b in enumerate(data):
            row.append(f"0x{b:02x}")
            if len(row) == 16:
                lines.append("    " + ",".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ",".join(row) + ",")
        lines.append(f"}};")
        lines.append(f"static const unsigned int {ident}_size = sizeof({ident});")
        lines.append("")

    lines.append("struct ThemeAsset { const char* name; const unsigned char* data; unsigned int size; };")
    lines.append("static const ThemeAsset kAssets[] = {")
    for name in ASSETS:
        ident = c_ident(name)
        lines.append(f"    {{ \"{name}\", {ident}, {ident}_size }},")
    lines.append("};")
    lines.append("static const unsigned int kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);")
    lines.append("")
    lines.append("inline const ThemeAsset* find(const char* name) {")
    lines.append("    for (unsigned int i = 0; i < kAssetCount; ++i)")
    lines.append("        if (std::strcmp(kAssets[i].name, name) == 0) return &kAssets[i];")
    lines.append("    return nullptr;")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace calf_theme")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({sum((SRC / n).stat().st_size for n in ASSETS)} bytes of PNG embedded)")

if __name__ == "__main__":
    emit()
